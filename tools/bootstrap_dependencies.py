#!/usr/bin/env python3
"""Build checksum-pinned dependencies locally; never installs into system directories."""
import argparse, hashlib, json, pathlib, subprocess, tarfile, tempfile, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]

def run(args):
    print('+', ' '.join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), check=True)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--jobs', type=int, default=2)
    parser.add_argument('--only', nargs='+')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'dependencies.lock.json').read_text())
    lock = manifest['sources']
    base = ROOT / '.deps'; prefix = base / 'install'
    for directory in ['downloads', 'src', 'build', 'install']:
        (base / directory).mkdir(parents=True, exist_ok=True)
    for name in ['eigen', 'boost', 'glog', 'suitesparse', 'ceres', 'opencv', 'cv_bridge']:
        if args.only and name not in args.only: continue
        entry = lock[name]
        archive = base / 'downloads' / (name + ('.tar.bz2' if name == 'boost' else '.tar.gz'))
        if not archive.exists():
            with urllib.request.urlopen(entry['url'], timeout=180) as response, archive.open('wb') as out:
                while chunk := response.read(1024 * 1024): out.write(chunk)
        if hashlib.file_digest(archive.open('rb'), 'sha256').hexdigest() != entry['sha256']:
            raise RuntimeError(f'Checksum mismatch: {archive}')
        source = base / 'src' / name
        if not source.exists():
            with tempfile.TemporaryDirectory(dir=base / 'src', prefix=name + '-') as temp:
                with tarfile.open(archive) as tar:
                    top = tar.getmembers()[0].name.split('/')[0]
                    tar.extractall(temp, filter='data')
                (pathlib.Path(temp) / top).rename(source)
        if name == 'boost':
            # Remaining uses are header-only: dynamic_bitset and uBLAS.
            dest = prefix / 'include' / 'boost'
            dest.parent.mkdir(parents=True, exist_ok=True)
            if not dest.exists(): dest.symlink_to(source / 'boost', target_is_directory=True)
            continue
        options = list(entry.get('cmake_options', []))
        if name == 'ceres':
            cmake = source / 'CMakeLists.txt'
            cmake.write_text(cmake.read_text().replace('find_package(Eigen3 3.3 REQUIRED)', 'find_package(Eigen3 5.0.1 EXACT REQUIRED CONFIG)'))
        if name == 'cv_bridge':
            source = source / 'cv_bridge'
            # Jazzy's bridge pins OpenCV 4 at configure time. Its used image API remains available.
            cmake = source / 'CMakeLists.txt'
            text = cmake.read_text().replace('find_package(OpenCV 4', 'find_package(OpenCV 5')
            text = text.replace('find_package(Boost REQUIRED)', 'add_library(Boost::headers INTERFACE IMPORTED)\n  set_target_properties(Boost::headers PROPERTIES INTERFACE_INCLUDE_DIRECTORIES "${CMAKE_INSTALL_PREFIX}/include")')
            cmake.write_text(text)
            header = source / 'include/cv_bridge/cv_bridge.hpp'
            header.write_text(header.read_text().replace('opencv2/imgproc/types_c.h', 'opencv2/imgproc.hpp'))
        build = base / 'build' / name
        if name == 'opencv': options += ['-DEigen3_DIR=' + str(prefix / 'share/eigen3/cmake')]
        run(['cmake', '-S', source, '-B', build, '-DCMAKE_BUILD_TYPE=Release', '-DCMAKE_CXX_STANDARD=' + str(manifest['cxx_standard']), '-DCMAKE_INSTALL_PREFIX=' + str(prefix), '-DCMAKE_PREFIX_PATH=' + str(prefix), '-DCMAKE_INSTALL_RPATH=' + str(prefix / 'lib'), *options])
        run(['cmake', '--build', build, '--parallel', args.jobs])
        run(['cmake', '--install', build])
        if name == 'cv_bridge':
            # A package installed by CMake still needs a prefix-level hook for colcon.
            (prefix / 'local_setup.bash').write_text(
                '# Generated by PL-VINS dependency bootstrap.\n'
                'source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/share/cv_bridge/local_setup.bash"\n')

if __name__ == '__main__': main()
